import { Logger } from '@nestjs/common';
import { NestFactory } from '@nestjs/core';
import { getConnectionToken } from '@nestjs/mongoose';
import type { OpenAPIObject } from '@nestjs/swagger';
import { dump } from 'js-yaml';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import type { Connection } from 'mongoose';
import { configureApp } from '../app.setup';
import { AppModule } from '../app.module';
import { buildSwaggerDocument } from '../swagger.setup';

// Standalone entry point, see the "openapi" npm script: writes the same OpenAPI document
// Swagger UI serves at /api/docs to <repo root>/docs/api/openapi.yaml. No HTTP server:
// the app is created but never initialised or started, so no scheduled job runs.

// Compiled to backend/dist/scripts/, so the repo root is three levels up.
const REPO_ROOT = resolve(__dirname, '..', '..', '..');
const OUTPUT = resolve(REPO_ROOT, 'docs', 'api', 'openapi.yaml');

const HEADER =
  '# Generated by `npm run openapi` from the NestJS Swagger decorators.\n' +
  '# Do not edit by hand: change the decorators and regenerate.\n';

const HTTP_METHODS = new Set([
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
]);

// Top-level keys in reading order; any other top-level key follows in its original order.
const TOP_LEVEL_ORDER = [
  'openapi',
  'info',
  'servers',
  'tags',
  'paths',
  'components',
];

// The same document with only its top-level keys reordered (absent keys skipped). Nothing
// inside them is touched.
function withTopLevelOrder(document: OpenAPIObject): Record<string, unknown> {
  const entries: [string, unknown][] = Object.entries(document);
  const first = TOP_LEVEL_ORDER.flatMap((key) =>
    entries.filter(([name]) => name === key),
  );
  const rest = entries.filter(([name]) => !TOP_LEVEL_ORDER.includes(name));
  return Object.fromEntries([...first, ...rest]);
}

function countOperations(document: OpenAPIObject): number {
  return Object.values(document.paths).reduce(
    (total, item) =>
      total + Object.keys(item).filter((key) => HTTP_METHODS.has(key)).length,
    0,
  );
}

async function exportOpenApi() {
  // Created like main.ts (rawBody), but quiet; abortOnError: false lets startup errors
  // reach the catch below.
  const app = await NestFactory.create(AppModule, {
    rawBody: true,
    logger: ['error', 'warn'],
    abortOnError: false,
  });
  try {
    // The /api prefix and the rest of the real configuration.
    configureApp(app);
    const document = buildSwaggerDocument(app);

    // Each compiled Mongoose model builds its indexes in the background. Wait for that
    // before closing, so the connection is not closed under it (as in swagger-docs e2e).
    const connection = app.get<Connection>(getConnectionToken());
    await Promise.all(
      Object.values(connection.models).map((model) => model.init()),
    );

    // Top-level keys in reading order; inside them, no anchors or aliases, no line
    // folding, the generated key order.
    const yaml = dump(withTopLevelOrder(document), {
      noRefs: true,
      lineWidth: -1,
      sortKeys: false,
    });
    mkdirSync(dirname(OUTPUT), { recursive: true });
    writeFileSync(OUTPUT, HEADER + yaml, 'utf8');

    const paths = Object.keys(document.paths).length;
    console.log(
      `Wrote ${relative(REPO_ROOT, OUTPUT).replaceAll('\\', '/')}: ` +
        `${paths} paths, ${countOperations(document)} operations`,
    );
  } finally {
    // Also closes the MongoDB connection.
    await app.close();
  }
}

// A connection error can name the cluster from MONGODB_URI: never print it.
function redact(message: string): string {
  return message
    .replace(/mongodb(\+srv)?:\/\/\S+/g, '<redacted>')
    .replace(/[\w.-]+\.mongodb\.net(:\d+)?/g, '<redacted>');
}

exportOpenApi().catch((error: unknown) => {
  const message = error instanceof Error ? error.message : String(error);
  new Logger('ExportOpenApi').error(
    `OpenAPI export failed: ${redact(message)}`,
  );
  process.exit(1);
});
