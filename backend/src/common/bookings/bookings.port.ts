import { BookingStatus, BookingType, ProviderType } from './booking-status';

/**
 * The contract between the platform modules (payments and accounts, C2) and
 * the two booking modules (flights, A1; hotels, B2). Nothing outside a booking
 * module reads or writes its booking collection: it asks through this port.
 *
 * That is what lets payments and account deactivation be built and tested
 * before the booking collections exist, and it keeps the inventory rules - how
 * seats and rooms are held and released - inside the module that owns them.
 *
 * To plug a module in: implement BookingsPort in one class, then provide it in
 * that module under FLIGHT_BOOKINGS_PORT or HOTEL_BOOKINGS_PORT and export the
 * token. Nothing in payments or accounts changes.
 */

/** The booking facts payments needs. A snapshot; payments never mutates it. */
export interface PayableBooking {
  bookingId: string;
  bookingType: BookingType;
  /** Owner of the booking, so payments can enforce ACC-11. */
  userId: string;
  status: BookingStatus;
  /**
   * Total to charge, as a decimal string such as "199.99", in the platform
   * currency (PAY-04). A string, not a number: money is Decimal128 in the
   * database and must never pass through a float.
   */
  totalAmount: string;
  currency: string;
  /** End of the 10-minute hold while PENDING_PAYMENT; null afterwards. */
  holdExpiresAt: Date | null;
  /** Generated on confirmation, so null while the booking is unpaid. */
  bookingReference: string | null;
  providerType: ProviderType;
  /** Airline id or hotel id, for the policy snapshot (PAY-02). */
  providerId: string;
}

/**
 * The provider terms that apply to one booking (PAY-02).
 *
 * These are the terms the booking itself carries - the snapshot taken when it
 * was created (HTL-09, FLT-09) - not the provider's latest ones. That is what
 * makes acceptance stable: a provider editing its policy during the 10-minute
 * hold cannot invalidate an acceptance the user has already given, and a later
 * edit never changes what an existing booking agreed to.
 */
export interface BookingPolicies {
  bookingId: string;
  bookingType: BookingType;
  providerType: ProviderType;
  providerId: string;
  /** The version this booking is on; the provider increments its own on edit. */
  policyVersion: number;
  /**
   * The exact terms, as shown to the user and stored with the acceptance. Its
   * shape is the provider's: baggage plus cancellation tiers for an airline,
   * cancellation tiers plus check-in and check-out times for a hotel.
   */
  policySnapshot: Record<string, unknown>;
}

export interface BookingConfirmation {
  bookingId: string;
  status: BookingStatus;
  /** Unique reference, generated by the booking module on confirmation. */
  bookingReference: string;
  /**
   * Optional: one line about what was booked, which the confirmation notice
   * (GEN-01) adds after the reference, e.g. "KD100 CAI to DXB on 20 Dec 2026,
   * 08:30; 3 passengers". Without it the notice names the reference and the
   * amount only.
   */
  summary?: string;
}

/** Why a hold is being released, for the booking module's own records. */
export enum HoldReleaseReason {
  /** The 10 minutes ran out (FLT-22, HTL-18). */
  HOLD_EXPIRED = 'HOLD_EXPIRED',
  /** Stripe reported the PaymentIntent as failed or cancelled. */
  PAYMENT_FAILED = 'PAYMENT_FAILED',
}

/**
 * ACC-17: how an admin narrows the list of every booking. The gateway decides
 * which modules are asked (the booking type), so a port only ever sees the
 * filters it applies to its own collection.
 */
export interface AdminBookingFilter {
  status?: BookingStatus;
  /** Bookings made at or after this instant (UTC). */
  createdFrom?: Date;
  /** Bookings made before this instant (UTC), exclusive. */
  createdTo?: Date;
  /** The exact booking reference, already upper-cased. */
  reference?: string;
  /**
   * The most rows to return, newest first. The gateway asks for
   * page x 10 rows, merges the two modules and keeps the page it needs, so a
   * port never has to know about pages.
   */
  limit: number;
}

/** ACC-17: one row of the admin booking list, from either module. */
export interface AdminBookingRow {
  bookingId: string;
  bookingType: BookingType;
  /** Null while the booking is unpaid: the reference is generated on payment. */
  bookingReference: string | null;
  /** The account that made the booking; the admin list resolves the name. */
  userId: string;
  providerType: ProviderType;
  providerId: string;
  /** Airline or hotel name; null when the provider row has gone. */
  providerName: string | null;
  /** Departure of the first segment, or the check-in date. */
  startsAt: Date;
  /** Arrival of the last segment, or the check-out date. */
  endsAt: Date;
  /** Decimal string such as "199.99" (money never passes through a float). */
  totalAmount: string;
  currency: string;
  status: BookingStatus;
  /** When the booking was made; the list is ordered by it, newest first. */
  createdAt: Date;
}

export interface AdminBookingList {
  /** At most `limit` rows, newest first. */
  rows: AdminBookingRow[];
  /** Every booking matching the filter, not only the rows returned. */
  total: number;
}

export interface BookingsPort {
  /**
   * The booking as it stands, or null when there is no such booking. Payments
   * checks ownership and state itself, so this must not filter by user.
   */
  findPayable(bookingId: string): Promise<PayableBooking | null>;

  /** The provider's current terms, for PAY-02. */
  findPolicies(bookingId: string): Promise<BookingPolicies | null>;

  /**
   * PENDING_PAYMENT -> CONFIRMED, called only from the verified Stripe
   * webhook. The implementation must:
   *  - be idempotent: a webhook Stripe retries must not confirm twice, and
   *    must return the same reference;
   *  - refuse to confirm once the hold has expired, because the inventory has
   *    already gone back (holdRelease in the schema's invariants);
   *  - convert the hold into a booking in one atomic step, so held and booked
   *    counters can never both be wrong.
   */
  confirmAfterPayment(
    bookingId: string,
    paymentId: string,
  ): Promise<BookingConfirmation>;

  /**
   * Gives the held seats or rooms back. Must release once only, however often
   * it is called: the expiry job and a failed-payment webhook can both arrive.
   */
  releaseHold(bookingId: string, reason: HoldReleaseReason): Promise<void>;

  /**
   * ACC-12: whether this account has a CONFIRMED booking whose travel or stay
   * has not happened yet. Deactivation is blocked while it has one, because a
   * deactivated account cannot log in to manage or cancel it.
   *
   * "Upcoming" is the booking module's own test: for a flight, a segment that
   * has not departed; for a hotel, a stay whose check-out has not passed.
   * Bookings in any other state do not count.
   */
  hasUpcomingConfirmedBookings(userId: string): Promise<boolean>;

  /**
   * ACC-17: the newest `filter.limit` bookings an admin may see, and how many
   * match in all. Read-only: the admin list never changes a booking.
   *
   * Ordered by createdAt descending, with the booking id as the tie-break, so
   * the gateway can merge the two modules into one stable page.
   *
   * Optional, and the only optional method here: the admin list arrived after
   * both booking modules did, so a port that has not implemented it yet still
   * satisfies this interface and still works for payments and ACC-12. The
   * gateway skips a port without it, and that booking type simply does not
   * appear in the admin list until its module implements this.
   */
  listForAdmin?(filter: AdminBookingFilter): Promise<AdminBookingList>;
}

/** Provided by the flights module (A1) once flight bookings exist. */
export const FLIGHT_BOOKINGS_PORT = 'FLIGHT_BOOKINGS_PORT';

/** Provided by the hotels module (B2) once hotel reservations exist. */
export const HOTEL_BOOKINGS_PORT = 'HOTEL_BOOKINGS_PORT';
